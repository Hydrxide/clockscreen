"""Weather icons as palette pixel art, 32px (current conditions) and 16px (forecasts).

Each grid row is a string; every character names a colour in ``PALETTE`` and ``.`` is
unlit. The grids were generated from shapes (discs, strokes) and touched up by hand, so
edit them directly. Kinds come from ``weather.codes``; clear and partly have day and
night versions.
"""

from __future__ import annotations

from .canvas import RGB, Canvas

PALETTE: dict[str, RGB] = {
    "Y": (255, 196, 0),    # sun
    "O": (255, 130, 0),    # sun rays
    "W": (235, 235, 235),  # cloud
    "G": (140, 140, 150),  # cloud underside / the cloud behind
    "D": (95, 95, 110),    # storm cloud
    "B": (60, 140, 255),   # rain
    "C": (190, 225, 255),  # snow and ice
    "M": (235, 225, 170),  # moon
    "L": (255, 225, 0),    # lightning
    "F": (165, 165, 165),  # fog
}

SIZES = (32, 16)


def icon_name(kind: str, is_day: bool) -> str:
    if kind in ("clear", "partly"):
        return f"{kind}_{'day' if is_day else 'night'}"
    return kind


def draw_icon(canvas: Canvas, x: int, y: int, kind: str, size: int, is_day: bool = True) -> None:
    """Draw the icon with its top-left at (x, y). Unknown kinds draw a cloud."""
    rows = _ICONS.get((icon_name(kind, is_day), size)) or _ICONS[("cloudy", size)]
    for dy, row in enumerate(rows):
        for dx, ch in enumerate(row):
            if ch != ".":
                canvas.set(x + dx, y + dy, PALETTE[ch])


